#!/usr/bin/env bash
# Build a self-contained, read-only harness volume.
#
#   images/harness/build.sh <name> <version|latest> <out_root>
#
# Produces <out_root>/<name>/<version>/ :
#   bin/<cli>        POSIX sh wrapper (the only path adapters call)
#   node/bin/node    bundled Node runtime (never taken from the workbench image)
#   pkg/             npm global prefix holding the harness package
#   manifest.json    {name, version, cli, sha256, package, entry, runtime, platform, built_at}
# and points <out_root>/<name>/current at it (relative symlink).
#
# The volume is mounted at /opt/harness/<name>/<version> in workbenches
# (PRSEC_HARNESS_HOME); the wrapper resolves everything relative to itself.
#
# Env:
#   NODE_IMAGE   builder image, also the source of the bundled node (default below)
#   PLATFORM     docker --platform for the build, e.g. linux/amd64 (default: host)
#   NPM_REGISTRY npm registry / mirror URL
#   ALLOW_SCRIPTS  extra comma-separated packages whose npm install scripts may run
#                  (npm >= 11 blocks dependency install scripts; the harness package itself
#                  is always allowed because claude-code/opencode place their native binary
#                  in postinstall)
#   FORCE=1      rebuild an existing <version>
#   SET_CURRENT=0  don't move the 'current' symlink
set -euo pipefail

NODE_IMAGE="${NODE_IMAGE:-node:24.22.1-bookworm-slim}"
SET_CURRENT="${SET_CURRENT:-1}"
FORCE="${FORCE:-0}"

usage() {
  echo "usage: $0 <claude-code|codex|opencode|pi> <version|latest> <out_root>" >&2
  exit 2
}

[[ $# -eq 3 ]] || usage
name=$1
version=$2
out_root=$3

case "$name" in
  claude-code) pkg="@anthropic-ai/claude-code"; cli=claude ;;
  codex) pkg="@openai/codex"; cli=codex ;;
  opencode) pkg="opencode-ai"; cli=opencode ;;
  pi) pkg="@mariozechner/pi-coding-agent"; cli=pi ;;
  *) echo "unknown harness: $name" >&2; usage ;;
esac

if [[ ! "$version" =~ ^(latest|[0-9]+\.[0-9]+\.[0-9]+([-+][0-9A-Za-z.-]+)?)$ ]]; then
  echo "invalid version: $version" >&2
  exit 2
fi

command -v docker >/dev/null || { echo "docker is required" >&2; exit 1; }

docker_args=(--rm --user "$(id -u):$(id -g)" -e HOME=/tmp/home -e npm_config_cache=/tmp/npm-cache
  -e npm_config_update_notifier=false -e npm_config_fund=false -e npm_config_audit=false)
[[ -n "${PLATFORM:-}" ]] && docker_args+=(--platform "$PLATFORM")
[[ -n "${NPM_REGISTRY:-}" ]] && docker_args+=(-e "npm_config_registry=$NPM_REGISTRY")

if [[ "$version" == latest ]]; then
  version=$(docker run "${docker_args[@]}" "$NODE_IMAGE" npm view "$pkg" version | tr -d '[:space:]')
  [[ -n "$version" ]] || { echo "could not resolve latest version of $pkg" >&2; exit 1; }
  echo "resolved $pkg@latest -> $version"
fi

mkdir -p "$out_root/$name"
name_dir=$(cd "$out_root/$name" && pwd -P)
final="$name_dir/$version"
if [[ -e "$final" && "$FORCE" != 1 ]]; then
  echo "$final already exists (FORCE=1 to rebuild)" >&2
  exit 1
fi

stage_name=".${version}.tmp.$$"
stage="$name_dir/$stage_name"
cleanup() { rm -rf -- "$stage"; }
trap cleanup EXIT
mkdir -p "$stage"

# Everything below runs inside the throwaway builder container; only /out is shared.
# shellcheck disable=SC2016  # expanded inside the container
inner='
set -euo pipefail
dest="/out/$STAGE"
mkdir -p /tmp/home "$dest/bin" "$dest/node/bin"
npm install --global --prefix "$dest/pkg" --allow-scripts="$ALLOW" "$PKG@$VERSION"

cp "$(command -v node)" "$dest/node/bin/node"
node_version=$(node --version)

link="$dest/pkg/bin/$CLI"
[[ -e "$link" ]] || { echo "package $PKG did not install a $CLI bin" >&2; exit 1; }
entry_abs=$(readlink -f "$link")
entry=${entry_abs#"$dest/"}

if head -n1 "$entry_abs" | grep -q "^#!.*node"; then
  runner="exec \"\$HERE/node/bin/node\" \"\$HERE/$entry\" \"\$@\""
else
  runner="exec \"\$HERE/$entry\" \"\$@\""
fi
cat > "$dest/bin/$CLI" <<EOF
#!/bin/sh
# prsec harness wrapper: $PKG@$VERSION (generated by images/harness/build.sh)
HERE=\$(CDPATH= cd -- "\$(dirname -- "\$0")/.." && pwd -P)
export PRSEC_HARNESS_NODE="\$HERE/node/bin/node"
$runner
EOF
chmod 0755 "$dest/bin/$CLI"

"$dest/bin/$CLI" --version >/dev/null 2>&1 || echo "warning: $CLI --version failed in builder" >&2

tree_sha=$(cd "$dest" && find . \( -type f -o -type l \) ! -path ./manifest.json -print0 \
  | LC_ALL=C sort -z \
  | while IFS= read -r -d "" f; do
      if [[ -L "$f" ]]; then printf "L %s %s\n" "$f" "$(readlink "$f")";
      else printf "F %s %s\n" "$f" "$(sha256sum < "$f" | cut -d" " -f1)"; fi
    done | sha256sum | cut -d" " -f1)

NODE_VERSION="$node_version" ENTRY="$entry" TREE_SHA="$tree_sha" node -e "
const e = process.env;
const m = {
  name: e.NAME, version: e.VERSION, cli: \"bin/\" + e.CLI, sha256: e.TREE_SHA,
  package: e.PKG, entry: e.ENTRY, runtime: \"node \" + e.NODE_VERSION,
  platform: process.platform + \"/\" + process.arch, built_at: new Date().toISOString(),
};
require(\"fs\").writeFileSync(\"$dest/manifest.json\", JSON.stringify(m, null, 2) + \"\\n\");
"
chmod -R a+rX,go-w "$dest"
'

docker run "${docker_args[@]}" \
  -v "$name_dir:/out" \
  -e STAGE="$stage_name" -e NAME="$name" -e PKG="$pkg" -e VERSION="$version" -e CLI="$cli" \
  -e ALLOW="$pkg${ALLOW_SCRIPTS:+,$ALLOW_SCRIPTS}" \
  "$NODE_IMAGE" bash -c "$inner"

if [[ -e "$final" ]]; then
  chmod -R u+w "$final"
  rm -rf -- "$final"
fi
mv -- "$stage" "$final"
trap - EXIT

if [[ "$SET_CURRENT" == 1 ]]; then
  ln -sfn -- "$version" "$name_dir/current"
fi

echo "built $final"
cat "$final/manifest.json"
